-- Money is stored as BIGINT minor units (cents). Never use floating point for money.

CREATE TABLE payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference     VARCHAR(64) NOT NULL UNIQUE,
    amount_minor  BIGINT      NOT NULL CHECK (amount_minor > 0),
    currency      VARCHAR(3)  NOT NULL,
    card_last4    VARCHAR(4),
    payment_date  DATE        NOT NULL
);

CREATE TABLE provider_transactions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider          VARCHAR(16) NOT NULL,
    external_id       VARCHAR(64) NOT NULL UNIQUE,
    reference         VARCHAR(64),
    amount_minor      BIGINT      NOT NULL,
    fee_minor         BIGINT      NOT NULL DEFAULT 0,
    currency          VARCHAR(3)  NOT NULL,
    card_last4        VARCHAR(4),
    transaction_date  DATE        NOT NULL
);

CREATE TABLE reconciliations (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id               BIGINT REFERENCES payments (id) ON DELETE CASCADE,
    provider_transaction_id  BIGINT REFERENCES provider_transactions (id) ON DELETE CASCADE,
    status                   VARCHAR(32) NOT NULL,
    confidence               INTEGER     NOT NULL,
    difference_minor         BIGINT      NOT NULL DEFAULT 0
);

CREATE INDEX idx_reconciliations_status ON reconciliations (status);
CREATE INDEX idx_provider_tx_reference ON provider_transactions (reference);
